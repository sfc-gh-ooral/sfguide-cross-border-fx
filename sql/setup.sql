-- ============================================================================
-- Cross-Border & FX - sql/setup.sql
-- ----------------------------------------------------------------------------
-- Cross-border settlement volume, FX margin (bps) and FX P&L by corridor for
-- the FX & treasury desk of a fictional payments processor.
--
-- FULLY SYNTHETIC. The corridor book and the FX series come from
-- data/generate.py (fixed seed), pasted below between the GENERATED DATA
-- markers, so every run loads identical numbers. Real FX rates are a paid
-- Snowflake Marketplace add-on; see "Go live" in the README.
--
-- Run top to bottom in one Snowsight worksheet. Needs ACCOUNTADMIN (or a role
-- that can create roles, warehouses and databases and grant
-- SNOWFLAKE.CORTEX_USER). Everything else runs as the pack role.
--
-- Creates: role CROSS_BORDER_FX_ROLE, warehouse SNOWPACK_CROSS_BORDER_FX_WH
-- (XSMALL, 60 s auto-suspend), database SNOWPACK_CROSS_BORDER_FX with schema
-- CORE: 3 tables, 2 views, a semantic view, a Cortex Agent, a notes table and
-- a stage for the Streamlit app. Remove it all with sql/cleanup.sql.
-- Cost: setup itself uses well under 0.1 warehouse credit (see README).
-- ============================================================================

-- 0. Least-privilege role ------------------------------------------------------
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS CROSS_BORDER_FX_ROLE
  COMMENT = 'Cross-Border & FX example: owns the pack objects, nothing else';
SET my_user = CURRENT_USER();
GRANT ROLE CROSS_BORDER_FX_ROLE TO USER IDENTIFIER($my_user);
GRANT CREATE DATABASE ON ACCOUNT TO ROLE CROSS_BORDER_FX_ROLE;
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE CROSS_BORDER_FX_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CROSS_BORDER_FX_ROLE;

-- 1. Warehouse, database, schema (owned by the pack role) -----------------------
USE ROLE CROSS_BORDER_FX_ROLE;
CREATE WAREHOUSE IF NOT EXISTS SNOWPACK_CROSS_BORDER_FX_WH
  WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Cross-Border & FX example';
USE WAREHOUSE SNOWPACK_CROSS_BORDER_FX_WH;
CREATE DATABASE IF NOT EXISTS SNOWPACK_CROSS_BORDER_FX COMMENT = 'Cross-Border & FX example (synthetic data)';
CREATE SCHEMA IF NOT EXISTS SNOWPACK_CROSS_BORDER_FX.CORE;
USE SCHEMA SNOWPACK_CROSS_BORDER_FX.CORE;

-- 2. Tables ------------------------------------------------------------------
-- One row per corridor; each corridor has a unique currency pair, so the FX
-- join below is strictly 1:1 with no fan-out.
CREATE OR REPLACE TABLE CROSS_BORDER_CORRIDOR (
  corridor_id STRING, origin_country STRING, dest_country STRING,
  currency_pair STRING, base_fx_rate FLOAT, corridor_name STRING
) COMMENT = 'Corridor dimension (synthetic)';

CREATE OR REPLACE TABLE CROSS_BORDER_FX_MONTHLY (
  currency_pair STRING, month_end DATE, fx_rate FLOAT
) COMMENT = 'SYNTHETIC FX rate by currency pair and month-end. To go live, replace with a view over a paid Marketplace FX listing exposing (currency_pair, month_end, fx_rate).';

CREATE OR REPLACE TABLE CROSS_BORDER_VOLUME_MONTHLY (
  corridor_id STRING, month_end DATE, cross_border_volume_usd NUMBER(18,0), txn_count NUMBER(12,0),
  settled_local_ccy NUMBER(20,0), fx_margin_bps NUMBER(6,1), fx_pnl_usd NUMBER(16,0)
) COMMENT = 'SYNTHETIC cross-border settlement volume, FX margin (bps) and FX P&L by corridor and month-end. fx_pnl_usd = volume x bps / 10000.';

